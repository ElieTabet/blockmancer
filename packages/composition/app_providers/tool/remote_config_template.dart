// Writes the Remote Config template and its key table from the code's own
// keys and defaults, so the console and the app can't disagree:
//
//   cd packages/composition/app_providers && dart run tool/remote_config_template.dart
//
// A test fails until this is re-run after a default or a key changes.
import 'dart:io';

import 'package:app_providers/src/remote_config_keys.dart';

void main() {
  final keys = remoteConfigKeys();

  File(
    '../../../docs/remote-config/template.json',
  ).writeAsStringSync(remoteConfigTemplate(keys));
  File('../../../docs/remote-config/keys.md').writeAsStringSync(
    '# Remote Config keys\n\n'
    'Generated by `packages/composition/app_providers/tool/'
    'remote_config_template.dart` from the code: every key the app reads, '
    'its type, the default it plays with (the template publishes exactly '
    'these), the values it accepts (anything else is ignored and the default '
    'plays) and what it changes. A run reads the values as it starts, so a '
    'published change reaches the next run, never one in progress.\n\n'
    '${remoteConfigTable(keys)}\n',
  );
}
